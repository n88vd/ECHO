"""Generate EchoIcons.kt (Compose ImageVectors) from icons/svg/*.svg.

Source icons: "Free Icon Pack 1800+ icons" (Figma Community), regular line style, 24x24.
Usage: python3 icons/gen_icons.py   (run from android/)
"""

import pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT.parent / "app/src/main/java/ai/echo/app/ui/theme/EchoIcons.kt"
NS = "{http://www.w3.org/2000/svg}"


def f(v: str | None, d: float = 0.0) -> float:
    return float(v) if v is not None else d


def shape_to_d(el: ET.Element) -> str:
    tag = el.tag.removeprefix(NS)
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag in ("circle", "ellipse"):
        cx, cy = f(a.get("cx")), f(a.get("cy"))
        rx = f(a.get("r")) if tag == "circle" else f(a.get("rx"))
        ry = f(a.get("r")) if tag == "circle" else f(a.get("ry"))
        return (f"M{cx - rx},{cy}A{rx},{ry} 0 1 1 {cx + rx},{cy}"
                f"A{rx},{ry} 0 1 1 {cx - rx},{cy}Z")
    if tag == "rect":
        x, y, w, h = f(a.get("x")), f(a.get("y")), f(a["width"]), f(a["height"])
        r = min(f(a.get("rx"), f(a.get("ry"))), w / 2, h / 2)
        if r == 0:
            return f"M{x},{y}H{x + w}V{y + h}H{x}Z"
        return (f"M{x + r},{y}H{x + w - r}A{r},{r} 0 0 1 {x + w},{y + r}V{y + h - r}"
                f"A{r},{r} 0 0 1 {x + w - r},{y + h}H{x + r}A{r},{r} 0 0 1 {x},{y + h - r}"
                f"V{y + r}A{r},{r} 0 0 1 {x + r},{y}Z")
    raise ValueError(f"unsupported element {tag}")


CAP = {"round": "StrokeCap.Round", "square": "StrokeCap.Square"}
MIRRORED = {"Back", "Send"}  # flip in RTL, like Icons.AutoMirrored
JOIN = {"round": "StrokeJoin.Round", "bevel": "StrokeJoin.Bevel"}


def icon(name: str, svg: pathlib.Path) -> str:
    lines = []
    for el in ET.parse(svg).getroot():
        a = el.attrib
        args = [f'pathData = addPathNodes("{shape_to_d(el)}")']
        if a.get("fill", "none") != "none":
            args.append("fill = ink")
        if a.get("fill-rule") == "evenodd":
            args.append("pathFillType = PathFillType.EvenOdd")
        if a.get("stroke", "none") != "none":
            args.append("stroke = ink")
            args.append(f'strokeLineWidth = {f(a.get("stroke-width"), 1.0)}f')
            if a.get("stroke-linecap") in CAP:
                args.append(f"strokeLineCap = {CAP[a['stroke-linecap']]}")
            if a.get("stroke-linejoin") in JOIN:
                args.append(f"strokeLineJoin = {JOIN[a['stroke-linejoin']]}")
        lines.append("            addPath(" + ", ".join(args) + ")")
    body = "\n".join(lines)
    return (f"    val {name}: ImageVector by lazy {{\n"
            f'        icon("{name}"{", autoMirror = true" if name in MIRRORED else ""}) {{\n{body}\n        }}\n    }}\n')


def main() -> None:
    icons = "\n".join(icon(p.stem, p) for p in sorted((ROOT / "svg").glob("*.svg")))
    OUT.write_text(f"""// GENERATED by android/icons/gen_icons.py from android/icons/svg — do not edit by hand.
// Icons: "Free Icon Pack 1800+ icons" (Figma Community).
package ai.echo.app.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

object EchoIcons {{
    // Icon() tints the whole vector, so the base colour only needs to be opaque.
    private val ink = SolidColor(Color.Black)

    private fun icon(name: String, autoMirror: Boolean = false, block: ImageVector.Builder.() -> Unit): ImageVector =
        ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f, autoMirror = autoMirror).apply(block).build()

{icons}}}
""")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
