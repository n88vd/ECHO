"""Generate the ECHO dot-sphere logo as Android vector drawables.

Writes the adaptive launcher foreground, the themed-icon monochrome layer and the
status-bar notification icon. Mirrors the in-app ParticleSphere (Fibonacci sphere,
depth-scaled dots, sky -> lavender -> pink from top to bottom).
Usage: python3 icons/gen_logo.py   (run from android/)
"""

import math
import pathlib

RES = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"

# Same as the in-app sphere: EchoColors.Sky, Lavender, Pink.
SKY, LAVENDER, PINK = (0x9B, 0xD2, 0xFF), (0xB9, 0xA8, 0xFF), (0xFF, 0xB3, 0xCC)


def sphere(n: int, yaw: float = 0.55, tilt: float = 0.45):
    golden = math.pi * (3 - math.sqrt(5))
    pts = []
    for i in range(n):
        y = 1 - 2 * (i + 0.5) / n
        r = math.sqrt(1 - y * y)
        x, z = math.cos(golden * i) * r, math.sin(golden * i) * r
        x1, z1 = x * math.cos(yaw) + z * math.sin(yaw), -x * math.sin(yaw) + z * math.cos(yaw)
        y2, z2 = y * math.cos(tilt) - z1 * math.sin(tilt), y * math.sin(tilt) + z1 * math.cos(tilt)
        pts.append((x1, y2, z2, y))
    return sorted(pts, key=lambda p: p[2])  # back to front


def lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def color(t: float):
    return lerp(SKY, LAVENDER, t * 2) if t < 0.5 else lerp(LAVENDER, PINK, (t - 0.5) * 2)


def circle(cx: float, cy: float, r: float) -> str:
    return f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0,1 1,{2 * r:.2f},0a{r:.2f},{r:.2f} 0,1 1,{-2 * r:.2f},0Z"


def dots(n, cx, cy, radius, rmin, rmax, fill):
    out = []
    for x, y, z, ylat in sphere(n):
        depth = (z + 1) / 2
        r = rmin + (rmax - rmin) * depth
        alpha = 0.22 + 0.78 * depth
        out.append(f'    <path android:pathData="{circle(cx + x * radius, cy + y * radius, r)}" '
                   f'android:fillColor="{fill((ylat + 1) / 2)}" android:fillAlpha="{alpha:.2f}" />')
    return "\n".join(out)


def vector(size: int, body: str, extra_ns: str = "") -> str:
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by android/icons/gen_logo.py -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}\n'
            f'    android:width="{size}dp" android:height="{size}dp" android:viewportWidth="{size}" android:viewportHeight="{size}">\n'
            f"{body}\n</vector>\n")


def hexc(rgb):
    return "#FF%02X%02X%02X" % rgb


def main() -> None:
    halo = ('    <path android:pathData="M54,54m-36,0a36,36 0,1 1,72 0a36,36 0,1 1,-72 0">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient android:type="radial" android:centerX="54" android:centerY="54" android:gradientRadius="36">\n'
            '                <item android:offset="0" android:color="#40B9A8FF" />\n'
            '                <item android:offset="1" android:color="#00B9A8FF" />\n'
            '            </gradient>\n        </aapt:attr>\n    </path>')
    # Adaptive icon: 108dp canvas, content kept inside the 66dp safe circle.
    fg = halo + "\n" + dots(220, 54, 54, 25, 0.7, 2.1, lambda t: hexc(color(t)))
    (RES / "ic_launcher_foreground.xml").write_text(
        vector(108, fg, ' xmlns:aapt="http://schemas.android.com/aapt"'))
    (RES / "ic_launcher_monochrome.xml").write_text(
        vector(108, dots(220, 54, 54, 25, 0.7, 2.1, lambda t: "#FFFFFFFF")))
    # Status bar icon: white only, alpha carries depth.
    (RES / "ic_stat_echo.xml").write_text(
        vector(24, dots(44, 12, 12, 9, 0.55, 1.35, lambda t: "#FFFFFFFF")))
    print("wrote launcher foreground, monochrome and notification icons")


if __name__ == "__main__":
    main()
